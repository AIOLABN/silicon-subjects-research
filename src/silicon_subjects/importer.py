from __future__ import annotations

import math
import operator
from collections import Counter
from collections.abc import Callable
from pathlib import Path
from typing import Any

import pandas as pd
import yaml

from .hashing import sha256_file

HEADER = "# GENERATED by `sim import-benchmark`; edit the import spec or its base, not this file.\n"

_OPS: dict[str, Callable[[float, float], bool]] = {
    ">": operator.gt,
    ">=": operator.ge,
    "<": operator.lt,
    "<=": operator.le,
}


class ImportError_(ValueError):
    pass


def _norm(v: Any) -> str | None:
    if v is None or (isinstance(v, float) and math.isnan(v)) or v is pd.NA:
        return None
    if isinstance(v, float) and v.is_integer():
        return str(int(v))
    text = str(v).strip()
    try:
        f = float(text)
        if f.is_integer():
            return str(int(f))
    except ValueError:
        pass
    return text or None


def read_raw(
    path: Path,
    file_format: str | None = None,
    encoding: str = "utf-8",
    encoding_errors: str = "strict",
) -> pd.DataFrame:
    fmt = (file_format or path.suffix.lstrip(".")).lower()
    if fmt in ("csv", "tsv"):
        try:
            return pd.read_csv(
                path,
                sep="\t" if fmt == "tsv" else ",",
                dtype=str,
                keep_default_na=True,
                encoding=encoding,
                encoding_errors=encoding_errors,
            )
        except UnicodeDecodeError as e:
            raise ImportError_(
                f"{path.name} is not valid {encoding} ({e.reason} at byte {e.start}); if only "
                "free-text columns are affected, set `encoding_errors: replace` in the spec"
            ) from e
    if fmt == "dta":
        return pd.read_stata(path, convert_categoricals=False)
    if fmt == "sav":
        try:
            return pd.read_spss(path, convert_categoricals=False)
        except ImportError as e:
            raise ImportError_("reading .sav needs `pip install pyreadstat`") from e
    raise ImportError_(f"unsupported file format {fmt!r} (csv, tsv, dta, sav)")


def _require(df: pd.DataFrame, cols: list[str]) -> None:
    if missing := [c for c in cols if c not in df.columns]:
        raise ImportError_(f"columns not in the raw file: {missing}")


def _derive(df: pd.DataFrame, spec: dict[str, Any]) -> pd.DataFrame:
    derive: dict[str, dict[str, list[str]]] = spec.get("derive") or {}
    if not derive:
        return df
    df = df.copy()
    for name, rule in derive.items():
        if set(rule) != {"coalesce"}:
            raise ImportError_(f"derive.{name}: only `coalesce: [columns]` is supported")
        cols = list(rule["coalesce"])
        _require(df, cols)
        if name in df.columns:
            raise ImportError_(f"derive.{name}: a raw column already has this name")
        normed = df[cols].map(_norm)
        df[name] = normed.bfill(axis=1).iloc[:, 0]
    return df


def _filter_mask(rows: pd.DataFrame, f: dict[str, Any]) -> pd.Series:
    col, op, value = f.get("column"), f.get("op"), f.get("value")
    if not isinstance(col, str) or op not in ("==", "!=", *_OPS):
        raise ImportError_(f"bad filter {f!r}: need column, op (== != > >= < <=) and value")
    if op in ("==", "!="):
        eq = rows[col].map(_norm) == _norm(value)
        return eq if op == "==" else ~eq
    try:
        threshold = float(str(value))
    except (TypeError, ValueError) as e:
        raise ImportError_(f"bad filter {f!r}: {op} needs a numeric value") from e
    num = pd.to_numeric(rows[col].map(_norm), errors="coerce")

    return num.map(lambda x: bool(not math.isnan(x) and _OPS[op](x, threshold)))


def compute(
    df: pd.DataFrame, spec: dict[str, Any], kind: str
) -> tuple[dict[str, Any], dict[str, Any], dict[str, Any]]:
    df = _derive(df, spec)
    cond_col, out_col = spec["condition_column"], spec["outcome_column"]
    site_col = spec.get("site_column")
    filters: list[dict[str, Any]] = spec.get("filters") or []
    flags: list[str] = spec.get("report_flags") or []
    _require(
        df,
        [
            cond_col,
            out_col,
            *([site_col] if site_col else []),
            *(spec.get("include") or {}).keys(),
            *(str(f.get("column")) for f in filters),
            *flags,
        ],
    )
    excluded: Counter[str] = Counter()
    rows = df
    for col, value in (spec.get("include") or {}).items():
        keep = rows[col].map(_norm) == _norm(value)
        excluded[f"include filter {col}={value}"] += int((~keep).sum())
        rows = rows[keep]
    for f in filters:
        keep = _filter_mask(rows, f)
        excluded[f"filter {f['column']} {f['op']} {f['value']}"] += int((~keep).sum())
        rows = rows[keep]
    cmap = {_norm(k): v for k, v in spec["condition_values"].items()}
    conds = rows[cond_col].map(lambda v: cmap.get(_norm(v)))
    excluded["unmapped condition"] += int(conds.isna().sum())
    rows, conds = rows[conds.notna()], conds[conds.notna()]
    outcome = (
        rows[out_col].map(_norm)
        if kind == "binary"
        else pd.to_numeric(rows[out_col].map(_norm), errors="coerce")
    )
    missing = outcome.isna()
    excluded["missing outcome"] += int(missing.sum())
    rows, conds, outcome = rows[~missing], conds[~missing], outcome[~missing]

    if kind == "binary":
        succ = {str(_norm(v)) for v in spec["success_values"]}
        fail = {str(_norm(v)) for v in spec["failure_values"]}
        if succ & fail:
            raise ImportError_(f"values listed as both success and failure: {sorted(succ & fail)}")
        known = outcome.isin(succ | fail)
        excluded["unrecognized outcome value"] += int((~known).sum())
        rows, conds, outcome = rows[known], conds[known], outcome[known]
        y = outcome.isin(succ).astype(int)

        def summary(mask: pd.Series) -> dict[str, dict[str, float]]:
            return {
                c: {"k": int(y[mask & (conds == c)].sum()), "n": int((mask & (conds == c)).sum())}
                for c in sorted(set(cmap.values()))
            }
    else:
        y = outcome.astype(float)

        def summary(mask: pd.Series) -> dict[str, dict[str, float]]:
            out = {}
            for c in sorted(set(cmap.values())):
                v = y[mask & (conds == c)]
                out[c] = {"mean": float(v.mean()), "sd": float(v.std(ddof=1)), "n": len(v)}
            return out

    everything = pd.Series(True, index=rows.index)
    fields: dict[str, Any] = {"conditions": summary(everything)}
    for c, s in fields["conditions"].items():
        if s["n"] == 0:
            raise ImportError_(f"condition {c!r} has no usable rows")
    if site_col:
        min_n = int(spec.get("min_site_n", 1))
        sites, dropped = [], 0
        for site, idx in rows.groupby(rows[site_col].map(_norm)).groups.items():
            mask = everything & rows.index.isin(idx)
            s = summary(mask)
            if all(v["n"] >= min_n for v in s.values()):
                sites.append({"site": site, "conditions": s})
            else:
                dropped += 1
        fields["sites"] = sites
        excluded[f"sites below min_site_n={min_n} (whole site, from the site list only)"] += dropped
    flagged = {
        col: {
            str(k): int(v) for k, v in sorted(rows[col].map(_norm).dropna().value_counts().items())
        }
        for col in flags
    }
    return fields, dict(excluded), flagged


def build(
    raw: Path, spec_path: Path, base: Path | None = None, root: Path | None = None
) -> tuple[dict[str, Any], str]:
    spec: dict[str, Any] = dict(yaml.safe_load(spec_path.read_text()))
    raw_sha = sha256_file(raw)
    accepted: dict[str, str] = spec.get("accepted_raw_sha256") or {}
    if accepted and raw_sha not in accepted:
        raise ImportError_(
            f"{raw.name} (sha256 {raw_sha[:12]}...) is not one of the raw files this spec accepts "
            f"({', '.join(accepted.values())}); fetch the pinned file with `sim sources fetch`"
        )
    base_path = base
    if spec.get("base"):
        base_path = Path(spec["base"])
        if not base_path.is_absolute():
            base_path = (root or Path.cwd()) / base_path
    if base_path is None:
        raise ImportError_("no base benchmark: give the spec a `base:` or pass one")
    bench: dict[str, Any] = dict(yaml.safe_load(base_path.read_text()))
    kind = bench.get("type", "binary")
    df = read_raw(
        raw,
        spec.get("file_format"),
        spec.get("encoding", "utf-8"),
        spec.get("encoding_errors", "strict"),
    )
    fields, excluded, flagged = compute(df, spec, kind)
    bench.update(fields)
    signoff = spec.get("signoff") or {}

    bench["verified"] = bool(signoff.get("verified", False))
    if signoff:
        bench["signoff"] = signoff
    bench["import_provenance"] = {
        "source": spec.get("source"),
        "raw_file": raw.name,
        "raw_label": accepted.get(raw_sha),
        "raw_sha256": raw_sha,
        "spec_file": spec_path.name,
        "spec_sha256": sha256_file(spec_path),
        "rows_in_file": len(df),
        "rows_used": int(sum(c["n"] for c in fields["conditions"].values())),
        "excluded": excluded,
        "flagged_rows_kept": flagged,
    }
    text = HEADER + yaml.safe_dump(bench, sort_keys=False, allow_unicode=True)
    return bench, text


def import_benchmark(
    base: Path | None,
    raw: Path,
    spec_path: Path,
    out: Path,
    *,
    write: bool = True,
    root: Path | None = None,
) -> dict[str, Any]:
    bench, text = build(raw, spec_path, base, root)
    if write:
        out.parent.mkdir(parents=True, exist_ok=True)
        tmp = out.with_suffix(out.suffix + ".tmp")
        tmp.write_text(text, encoding="utf-8", newline="\n")
        tmp.replace(out)
    return bench


def matches_existing(
    raw: Path, spec_path: Path, out: Path, base: Path | None = None, root: Path | None = None
) -> bool:
    _, text = build(raw, spec_path, base, root)
    return out.exists() and out.read_text() == text
